"""Fail closed if an ACC wheel contains anything outside the source payload allowlist."""
import json
import sys
import zipfile
from pathlib import PurePosixPath

def verify(wheel, manifest):
    allowed = {name.removeprefix('src/') for name in manifest['acc'] if name.startswith('src/')}
    found = set()
    with zipfile.ZipFile(wheel) as archive:
        for entry in archive.infolist():
            name = entry.filename
            parts = PurePosixPath(name).parts
            if name.startswith('/') or '\\' in name or '..' in parts:
                raise ValueError('Unsafe wheel path: ' + name)
            if entry.is_dir():
                continue
            if name in allowed:
                found.add(name)
                continue
            # Wheel metadata is generated by setuptools, never executable payload.
            if len(parts) >= 2 and parts[0].startswith('ai_computer_control-') and parts[0].endswith('.dist-info'):
                if '/'.join(parts[1:]) in {'METADATA', 'WHEEL', 'RECORD', 'entry_points.txt', 'top_level.txt', 'LICENSE', 'licenses/LICENSE'}:
                    continue
            raise ValueError('Unexpected ACC wheel payload: ' + name)
    if found != allowed:
        raise ValueError('Missing ACC wheel modules: ' + ', '.join(sorted(allowed - found)))

if __name__ == '__main__':
    with open(sys.argv[2], encoding='utf-8') as source:
        verify(sys.argv[1], json.load(source))
    print('ACC wheel allowlist verified')
